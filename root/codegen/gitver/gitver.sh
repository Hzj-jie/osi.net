#!/usr/bin/env bash
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../../.." && pwd)"

FORMAT="CommitHash:%H  |-+-|  ShortCommitHash:%h  |-+-|  Author:%an  |-+-|  AuthorEMail:%ae  |-+-|  AuthorDate:%ad  |-+-|  Committer:%cn  |-+-|  CommitterEMail:%ce  |-+-|  CommitterDate:%cd  |-+-|  Subject:%s  |-+-|  Body:%b"

cd "$REPO_DIR"

LATEST_COMMIT=$(git log -1 origin/master --pretty=format:"$FORMAT" 2>/dev/null || git log -1 --pretty=format:"$FORMAT" 2>/dev/null || echo "")
CURRENT_COMMIT=$(git log -1 --pretty=format:"$FORMAT" 2>/dev/null || echo "")
BRANCH=$(git branch --show-current 2>/dev/null || echo "")
DIFF_BASE64=$(git diff --ignore-all-space 2>/dev/null | base64 | tr -d "\r\n" 2>/dev/null || echo "")

# Escape quotes for VB string literal
LATEST_COMMIT_ESC="${LATEST_COMMIT//\"/\"\"}"
CURRENT_COMMIT_ESC="${CURRENT_COMMIT//\"/\"\"}"

echo "'this file is generated by /osi/root/codegen/gitver/gitver.sh"
echo "'so change the script instead of this file"
echo ""
echo "Partial Public NotInheritable Class gitver"
echo "    Public Shared ReadOnly latest_commit_raw As String = _"
echo "        \"$LATEST_COMMIT_ESC\".Trim()"
echo "    Public Shared ReadOnly current_commit_raw As String = _"
echo "        \"$CURRENT_COMMIT_ESC\".Trim()"
echo "    Public Shared ReadOnly diff_base64 As String = _"
echo "        \"$DIFF_BASE64\""
echo "    Public Shared ReadOnly branch As String = _"
echo "        \"$BRANCH\".Trim()"
echo "End Class"
